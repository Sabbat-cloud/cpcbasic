def encode_byte(p0, p1):
    b = 0
    b |= ((p0 >> 0) & 1) << 7
    b |= ((p1 >> 0) & 1) << 6
    b |= ((p0 >> 2) & 1) << 5
    b |= ((p1 >> 2) & 1) << 4
    b |= ((p0 >> 1) & 1) << 3
    b |= ((p1 >> 1) & 1) << 2
    b |= ((p0 >> 3) & 1) << 1
    b |= ((p1 >> 3) & 1) << 0
    return b


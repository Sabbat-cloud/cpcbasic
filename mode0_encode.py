for s, data in enumerate(sprites):
    out = []
    for row in range(8):
        for col in range(0, 8, 2):
            p0 = data[row * 8 + col]
            p1 = data[row * 8 + col + 1]
            out.append(str(encode_byte(p0, p1)))
